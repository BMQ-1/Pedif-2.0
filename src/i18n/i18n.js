class I18nManager {
  constructor() {
    this.locale = this.detectLocale();
    this.listeners = new Set();
  }

  detectLocale() {
    try {
      const saved = localStorage.getItem('pedif_locale');
      if (saved && TRANSLATIONS[saved]) return saved;
      const navLang = (navigator.language || navigator.userLanguage || 'en').split('-')[0].toLowerCase();
      if (TRANSLATIONS[navLang]) return navLang;
    } catch {}
    return 'en';
  }

  getLocale() {
    return this.locale;
  }

  get currentLang() {
    return this.locale;
  }

  setLocale(code) {
    if (!TRANSLATIONS[code]) return;
    this.locale = code;
    try {
      localStorage.setItem('pedif_locale', code);
    } catch {}

    const locObj = SUPPORTED_LOCALES.find(l => l.code === code);
    const dir = locObj ? locObj.dir : 'ltr';

    if (typeof document !== 'undefined') {
      document.documentElement.lang = code;
      document.documentElement.dir = dir;
      document.body.classList.toggle('rtl-mode', dir === 'rtl');
    }

    this.notify();
  }

  setLanguage(code) {
    return this.setLocale(code);
  }

  isRtl() {
    const locObj = SUPPORTED_LOCALES.find(l => l.code === this.locale);
    return locObj ? locObj.dir === 'rtl' : false;
  }

  t(key) {
    const table = TRANSLATIONS[this.locale] || TRANSLATIONS.en;
    if (table[key] !== undefined) return table[key];
    return TRANSLATIONS.en[key] || key;
  }

  onChange(fn) {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }

  notify() {
    this.listeners.forEach(fn => {
      try { fn(this.locale); } catch (e) { console.warn('[i18n] listener error:', e); }
    });
  }
}

export const i18n = new I18nManager();
export const t = (k) => i18n.t(k);
